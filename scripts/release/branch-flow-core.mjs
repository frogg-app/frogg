// Pure rules behind branch-flow.mjs: which version a branch keeps after a
// merge, what beta promotes to, and which conflicts the version restamp fixes.
import { BETA_BRANCH, compareCoreVersions, requiredBranchForVersion } from "./release-branches.mjs";
import { parseReleaseVersion } from "./release-version-utils.mjs";

export function resolveSyncedVersion({ targetBranch, preMergeVersion }) {
  if (requiredBranchForVersion(preMergeVersion) !== targetBranch) {
    throw new Error(
      targetBranch === BETA_BRANCH
        ? `beta must carry a -beta.N version, found ${preMergeVersion}.`
        : `${targetBranch} must carry a stable version, found ${preMergeVersion}.`,
    );
  }
  return preMergeVersion;
}

export function promotionVersion({ betaVersion, mainVersion }) {
  const beta = parseReleaseVersion(betaVersion);
  if (!beta.isPrerelease) throw new Error(`origin/beta is ${betaVersion}, not a beta.`);
  if (compareCoreVersions(beta, parseReleaseVersion(mainVersion)) <= 0) {
    throw new Error(`Beta base ${beta.baseVersion} is not above main ${mainVersion}.`);
  }
  return beta.baseVersion;
}

// Lockfiles are regenerated by the restamp, so a conflict there resolves to
// either side. The manifests still need a human when they conflict on more
// than the version line.
export const REGENERATED_PATHS = new Set(["package-lock.json", "Cargo.lock", "npm-deps.hash"]);

export function isVersionOwnedPath(file) {
  const base = file.split("/").pop();
  return base === "package.json" || base === "Cargo.toml" || REGENERATED_PATHS.has(base);
}

export function isRegeneratedPath(file) {
  return REGENERATED_PATHS.has(file.split("/").pop());
}
