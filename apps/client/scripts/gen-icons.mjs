#!/usr/bin/env node
// Dev-time generator: inlines every lucide icon apps/ui-next imports as Rust SVG data
// (apps/client/ui/src/components/icon_data.rs). Nothing here ships; rerun when ui-next adds one.
//   node apps/client/scripts/gen-icons.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const require = createRequire(join(root, "package.json"));
const lucideDir = join(dirname(require.resolve("lucide-react-native/package.json")), "dist/esm");

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(name)) out.push(p);
  }
  return out;
}

const names = new Set();
for (const file of walk(join(root, "apps/ui-next/src"))) {
  const src = readFileSync(file, "utf8");
  for (const m of src.matchAll(/import\s*{([^}]*)}\s*from\s*"lucide-react-native"/g))
    for (const part of m[1].split(",")) {
      const n = part
        .replace(/^\s*type\s+/, "")
        .split(/\s+as\s+/)[0]
        .trim();
      if (n && n !== "LucideIcon" && !/^type\b/.test(part.trim())) names.add(n);
    }
}
// Shell extras the port needs beyond ui-next's imports.
for (const n of ["Plus", "QrCode", "Upload", "Zap", "Check", "Trash2", "Wifi", "WifiOff"])
  names.add(n);

const index = readFileSync(join(lucideDir, "lucide-react-native.js"), "utf8");
const attr = (k, v) =>
  `${k === "key" ? "" : `${k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}="${v}"`}`;
const entries = [];
for (const name of [...names].sort()) {
  const m = new RegExp(`default as ${name}(?:,| })[^\\n]*from '\\./icons/([a-z0-9-]+)\\.js'`).exec(
    index,
  );
  if (!m) {
    console.warn(`skip ${name}: not in lucide`);
    continue;
  }
  const js = readFileSync(join(lucideDir, "icons", `${m[1]}.js`), "utf8");
  const body = js.slice(js.indexOf("["), js.lastIndexOf("]") + 1);
  const nodes = Function(`return ${body}`)();
  const svg = nodes
    .map(
      ([tag, a]) =>
        `<${tag} ${Object.entries(a)
          .map(([k, v]) => attr(k, v))
          .filter(Boolean)
          .join(" ")}/>`,
    )
    .join("");
  entries.push([name, svg]);
}

const out = `// @generated by apps/client/scripts/gen-icons.mjs from lucide (ISC). Do not edit by hand.
#![allow(clippy::all)]

/// Every lucide icon apps/ui-next uses, by its lucide name.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Ico {
${entries.map(([n]) => `    ${n},`).join("\n")}
}

impl Ico {
    /// The icon's inner SVG markup on lucide's 24×24 grid.
    pub fn body(self) -> &'static str {
        match self {
${entries.map(([n, s]) => `            Ico::${n} => r#"${s}"#,`).join("\n")}
        }
    }
}
`;
writeFileSync(join(root, "apps/client/ui/src/components/icon_data.rs"), out);
console.log(`${entries.length} icons`);
